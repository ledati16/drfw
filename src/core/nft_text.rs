//! Renders drfw's nftables JSON commands as an `nft -f` text file
//!
//! The text output (GUI preview and diff, `drfw export --format nft`, Save to
//! System) used to be a separately hand-written renderer that drifted from the
//! JSON that is actually applied. This module instead renders the **same**
//! command list that [`FirewallRuleset::to_nftables_json`] produces, so the two
//! can only differ in syntax, never in meaning. `tests/real_nft.rs` checks that
//! loading either form into the kernel yields identical rulesets.
//!
//! Only the expression subset drfw emits is supported: matches on `meta`, `ct`,
//! `payload` and `fib` (values: strings, numbers, sets, prefixes, ranges),
//! `limit` (burst, inverted), `ct count` (inverted), `log`, `counter`, and the
//! `accept`/`drop`/`reject` verdicts. Anything else is a programming error; it
//! is rendered as an invalid statement so that `nft -c` rejects the file
//! instead of silently loading a rule with a match missing.
//!
//! # Output format
//!
//! ```text
//! #!/usr/sbin/nft -f
//! # Generated by DRFW … do not edit by hand
//! table inet drfw
//! delete table inet drfw
//!
//! table inet drfw {
//!     chain input {
//!         type filter hook input priority -10; policy drop;
//!         …
//!     }
//! }
//! ```
//!
//! `table …` followed by `delete table …` is the idempotent replace idiom: the
//! first line guarantees the table exists so the delete cannot fail, and the
//! whole file is one transaction. It works on every nft version, unlike
//! `destroy table` (nft >= 1.0.8). The JSON side uses `add` + `flush` instead,
//! which is equivalent for drfw's fixed chain layout.
//!
//! [`FirewallRuleset::to_nftables_json`]: crate::core::firewall::FirewallRuleset::to_nftables_json

use crate::core::firewall::NftCommand;
use serde_json::Value;
use std::fmt::Write;

/// Indentation for chain blocks inside the table block.
/// Start of the second line of every generated file, followed by the DRFW
/// version. `drfw status` uses it to tell whether the system config is ours.
pub const GENERATED_HEADER: &str = "# Generated by DRFW";

/// Returns the DRFW version named in the header of a generated nft file, or
/// `None` if `head` (the start of the file) was not written by DRFW.
///
/// # Example
///
/// ```
/// use drfw::core::nft_text::generated_by_drfw;
///
/// let file = "#!/usr/sbin/nft -f\n# Generated by DRFW 0.9.0 -- do not edit\n";
/// assert_eq!(generated_by_drfw(file), Some("0.9.0"));
/// assert_eq!(generated_by_drfw("#!/usr/sbin/nft -f\nflush ruleset\n"), None);
/// ```
pub fn generated_by_drfw(head: &str) -> Option<&str> {
    head.lines().take(2).find_map(|line| {
        let rest = line.strip_prefix(GENERATED_HEADER)?.strip_prefix(' ')?;
        rest.split_whitespace().next()
    })
}

const CHAIN_INDENT: &str = "    ";
/// Indentation for rules inside a chain block.
const RULE_INDENT: &str = "        ";
/// Statement that nft is guaranteed to reject. Emitted in place of a rule that
/// could not be rendered, so a broken file can never be loaded.
const RENDER_ERROR_STATEMENT: &str = "drfw-render-error";
/// Burst nft applies to a packet `limit` that does not specify one.
const NFT_DEFAULT_LIMIT_BURST: u64 = 5;

/// A chain block being assembled.
struct ChainBlock {
    name: String,
    declaration: Option<String>,
    lines: Vec<String>,
    last_section: Option<&'static str>,
}

/// Renders an annotated command list (see `FirewallRuleset::build_commands`)
/// as a standalone `nft -f` file.
///
/// Never fails: commands or expressions outside the supported subset are
/// logged and rendered as an invalid statement (see module docs).
pub(crate) fn render(commands: &[NftCommand]) -> String {
    let mut preamble: Vec<String> = Vec::new();
    let mut table: Option<(String, String)> = None;
    let mut chains: Vec<ChainBlock> = Vec::new();
    let mut errors: Vec<String> = Vec::new();

    for command in commands {
        if let Err(e) = apply_command(command, &mut preamble, &mut table, &mut chains) {
            tracing::error!("nft text renderer: {e}");
            errors.push(e);
        }
    }

    let mut out =
        String::with_capacity(512 + chains.iter().map(|c| c.lines.len() * 96).sum::<usize>());
    out.push_str("#!/usr/sbin/nft -f\n");
    let _ = writeln!(
        out,
        "{GENERATED_HEADER} {} -- do not edit by hand; changes are overwritten.",
        env!("CARGO_PKG_VERSION")
    );
    out.push_str("# Loading this file replaces the whole \"inet drfw\" table.\n");
    for e in &errors {
        let _ = writeln!(out, "# DRFW internal error: {}", single_line(e));
        let _ = writeln!(out, "{RENDER_ERROR_STATEMENT}");
    }
    for line in &preamble {
        out.push_str(line);
        out.push('\n');
    }

    let Some((family, name)) = table else {
        return out;
    };

    let _ = writeln!(out, "\ntable {family} {name} {{");
    for (i, chain) in chains.iter().enumerate() {
        if i > 0 {
            out.push('\n');
        }
        let _ = writeln!(out, "{CHAIN_INDENT}chain {} {{", chain.name);
        if let Some(decl) = &chain.declaration {
            let _ = writeln!(out, "{RULE_INDENT}{decl}");
        }
        for line in &chain.lines {
            if line.is_empty() {
                out.push('\n');
            } else {
                let _ = writeln!(out, "{RULE_INDENT}{line}");
            }
        }
        let _ = writeln!(out, "{CHAIN_INDENT}}}");
    }
    out.push_str("}\n");
    out
}

/// Applies one command to the document being assembled.
fn apply_command(
    command: &NftCommand,
    preamble: &mut Vec<String>,
    table: &mut Option<(String, String)>,
    chains: &mut Vec<ChainBlock>,
) -> Result<(), String> {
    let (verb, body) = single_entry(&command.value).ok_or("malformed command")?;
    let (object, spec) = single_entry(body).ok_or("malformed command body")?;

    match (verb, object) {
        ("add", "table") => {
            let family = str_field(spec, "family")?;
            let name = str_field(spec, "name")?;
            check_table(table, family, name)?;
            preamble.push(format!("table {family} {name}"));
            Ok(())
        }
        ("flush", "table") => {
            let family = str_field(spec, "family")?;
            let name = str_field(spec, "name")?;
            check_table(table, family, name)?;
            preamble.push(format!("delete table {family} {name}"));
            Ok(())
        }
        ("add", "chain") => {
            let name = symbol(str_field(spec, "name")?)?;
            let declaration = if spec.get("hook").is_some() {
                let chain_type = symbol(str_field(spec, "type")?)?;
                let hook = symbol(str_field(spec, "hook")?)?;
                let prio = spec
                    .get("prio")
                    .and_then(Value::as_i64)
                    .ok_or("chain without numeric priority")?;
                let policy = symbol(str_field(spec, "policy")?)?;
                Some(format!(
                    "type {chain_type} hook {hook} priority {prio}; policy {policy};"
                ))
            } else {
                None
            };
            let block = chain_block(chains, name);
            block.declaration = declaration;
            Ok(())
        }
        ("add", "rule") => {
            let chain = symbol(str_field(spec, "chain")?)?;
            let line = render_rule(spec);
            let block = chain_block(chains, chain);
            if block.last_section != Some(command.section) {
                block.lines.push(String::new());
                block.lines.push(format!("# --- {} ---", command.section));
                block.last_section = Some(command.section);
            }
            match line {
                Ok(line) => block.lines.push(line),
                Err(e) => {
                    block
                        .lines
                        .push(format!("# DRFW internal error: {}", single_line(&e)));
                    block.lines.push(RENDER_ERROR_STATEMENT.to_string());
                    return Err(e);
                }
            }
            Ok(())
        }
        _ => Err(format!("unsupported command `{verb} {object}`")),
    }
}

/// Records the table name; drfw only ever manages a single table.
fn check_table(
    table: &mut Option<(String, String)>,
    family: &str,
    name: &str,
) -> Result<(), String> {
    let family = symbol(family)?;
    let name = symbol(name)?;
    match table {
        Some((f, n)) if f != family || n != name => {
            Err("commands for more than one table".to_string())
        }
        Some(_) => Ok(()),
        None => {
            *table = Some((family.to_string(), name.to_string()));
            Ok(())
        }
    }
}

/// Returns the chain block named `name`, creating it if needed.
fn chain_block<'a>(chains: &'a mut Vec<ChainBlock>, name: &str) -> &'a mut ChainBlock {
    let index = if let Some(i) = chains.iter().position(|c| c.name == name) {
        i
    } else {
        chains.push(ChainBlock {
            name: name.to_string(),
            declaration: None,
            lines: Vec::new(),
            last_section: None,
        });
        chains.len() - 1
    };
    &mut chains[index]
}

/// Renders one `add rule` body as a statement line.
fn render_rule(spec: &Value) -> Result<String, String> {
    let exprs = spec
        .get("expr")
        .and_then(Value::as_array)
        .ok_or("rule without expression list")?;
    let mut parts = Vec::with_capacity(exprs.len() + 1);
    for expr in exprs {
        parts.push(render_statement(expr)?);
    }
    if let Some(comment) = spec.get("comment").and_then(Value::as_str) {
        parts.push(format!("comment {}", quoted(comment)));
    }
    Ok(parts.join(" "))
}

/// Renders a single statement (match, limit, verdict, ...).
fn render_statement(expr: &Value) -> Result<String, String> {
    let (key, body) = single_entry(expr).ok_or("malformed expression")?;
    match key {
        "match" => render_match(body),
        "limit" => {
            check_keys(body, &["rate", "per", "burst", "inv"], "limit")?;
            let rate = u64_field(body, "rate")?;
            let per = symbol(str_field(body, "per")?)?;
            let over = if is_inverted(body) { "over " } else { "" };
            // Always spell out the burst. Without one, the kernel applies nft's
            // default of 5 packets (the listing shows `burst 5 packets`), so the
            // explicit form loads the identical rule. It also avoids an nft 1.1.7
            // parser bug: `limit rate over N/unit reject with tcp reset comment ".."`
            // (no burst) is rejected as "unexpected junk".
            let burst = match body.get("burst") {
                Some(burst) => burst.as_u64().ok_or("non-numeric limit burst")?,
                None => NFT_DEFAULT_LIMIT_BURST,
            };
            Ok(format!(
                "limit rate {over}{rate}/{per} burst {burst} packets"
            ))
        }
        "ct count" => {
            check_keys(body, &["val", "inv"], "ct count")?;
            let val = u64_field(body, "val")?;
            let over = if is_inverted(body) { "over " } else { "" };
            Ok(format!("ct count {over}{val}"))
        }
        "log" => {
            check_keys(body, &["prefix", "level"], "log")?;
            let mut s = String::from("log");
            if let Some(prefix) = body.get("prefix") {
                let prefix = prefix.as_str().ok_or("non-string log prefix")?;
                let _ = write!(s, " prefix {}", quoted(prefix));
            }
            if let Some(level) = body.get("level") {
                let level = symbol(level.as_str().ok_or("non-string log level")?)?;
                let _ = write!(s, " level {level}");
            }
            Ok(s)
        }
        "counter" | "accept" | "drop" if body.is_null() => Ok(key.to_string()),
        "reject" => render_reject(body),
        _ => Err(format!("unsupported expression `{key}`")),
    }
}

/// Renders a `reject` verdict.
fn render_reject(body: &Value) -> Result<String, String> {
    if body.is_null() {
        return Ok("reject".to_string());
    }
    check_keys(body, &["type", "expr"], "reject")?;
    match str_field(body, "type")? {
        "tcp reset" => Ok("reject with tcp reset".to_string()),
        reject_type @ ("icmpx" | "icmp" | "icmpv6") => {
            let code = symbol(str_field(body, "expr")?)?;
            Ok(format!("reject with {reject_type} type {code}"))
        }
        other => Err(format!("unsupported reject type `{other}`")),
    }
}

/// Renders a `match` statement: `<left> [!= ]<right>`.
fn render_match(body: &Value) -> Result<String, String> {
    let left = body.get("left").ok_or("match without left side")?;
    let right = body.get("right").ok_or("match without right side")?;
    let op = match body.get("op").and_then(Value::as_str) {
        Some("==") => "",
        Some("!=") => "!= ",
        other => return Err(format!("unsupported match operator {other:?}")),
    };

    let (kind, spec) = single_entry(left).ok_or("malformed match left side")?;
    let (left_text, right_text) = match kind {
        "meta" => {
            let key = symbol(str_field(spec, "key")?)?;
            // Interface names are strings and must be quoted; everything else
            // drfw matches on meta keys is a symbolic constant.
            let quote = matches!(key, "iifname" | "oifname");
            let left = if matches!(key, "iifname" | "oifname" | "pkttype") {
                key.to_string()
            } else {
                format!("meta {key}")
            };
            (left, render_value(right, quote)?)
        }
        "ct" => {
            let key = symbol(str_field(spec, "key")?)?;
            // `ct state` is a bitmask: in text, `ct state invalid` means "bit
            // set" (JSON op `in`), not equality. Keep JSON `==` exact by
            // spelling the operator out.
            let explicit_eq = op.is_empty() && !right.get("set").is_some_and(Value::is_array);
            let left = if explicit_eq {
                format!("ct {key} ==")
            } else {
                format!("ct {key}")
            };
            (left, render_value(right, false)?)
        }
        "payload" => {
            let protocol = symbol(str_field(spec, "protocol")?)?;
            let field = symbol(str_field(spec, "field")?)?;
            (format!("{protocol} {field}"), render_value(right, false)?)
        }
        "fib" => {
            let mut flags = Vec::new();
            for flag in spec
                .get("flags")
                .and_then(Value::as_array)
                .ok_or("fib without flags")?
            {
                flags.push(symbol(flag.as_str().ok_or("non-string fib flag")?)?);
            }
            let result = symbol(str_field(spec, "result")?)?;
            let right = match right {
                Value::Bool(false) => "missing".to_string(),
                Value::Bool(true) => "exists".to_string(),
                other => render_value(other, false)?,
            };
            (format!("fib {} {result}", flags.join(" . ")), right)
        }
        other => return Err(format!("unsupported match on `{other}`")),
    };
    Ok(format!("{left_text} {op}{right_text}"))
}

/// Renders the right-hand side of a match.
///
/// `quote` selects quoted strings (interface names); otherwise strings must be
/// plain symbols or addresses.
fn render_value(value: &Value, quote: bool) -> Result<String, String> {
    match value {
        Value::String(s) if quote => Ok(quoted(s)),
        Value::String(s) => symbol(s).map(str::to_string),
        Value::Number(n) => Ok(n.to_string()),
        Value::Object(_) => {
            let (kind, body) = single_entry(value).ok_or("malformed value object")?;
            match kind {
                "set" => {
                    let items = body.as_array().ok_or("set is not a list")?;
                    let rendered = items
                        .iter()
                        .map(|item| render_value(item, quote))
                        .collect::<Result<Vec<_>, _>>()?;
                    Ok(format!("{{ {} }}", rendered.join(", ")))
                }
                "prefix" => {
                    let addr = symbol(str_field(body, "addr")?)?;
                    let len = u64_field(body, "len")?;
                    Ok(format!("{addr}/{len}"))
                }
                "range" => {
                    let bounds = body.as_array().ok_or("range is not a list")?;
                    let [start, end] = bounds.as_slice() else {
                        return Err("range must have two bounds".to_string());
                    };
                    Ok(format!(
                        "{}-{}",
                        render_value(start, quote)?,
                        render_value(end, quote)?
                    ))
                }
                other => Err(format!("unsupported value `{other}`")),
            }
        }
        other => Err(format!("unsupported value {other}")),
    }
}

/// Quotes a string for nft, removing characters a quoted string cannot hold.
fn quoted(s: &str) -> String {
    format!("\"{}\"", crate::validators::sanitize_nft_quoted(s))
}

/// Accepts a bare nft word: keywords, symbolic constants, addresses.
///
/// Anything else (spaces, quotes, braces, ...) means the JSON contains
/// something the renderer does not understand; refusing it keeps arbitrary
/// text out of the file.
fn symbol(s: &str) -> Result<&str, String> {
    let ok = !s.is_empty()
        && s.chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.' | ':' | '/'));
    if ok {
        Ok(s)
    } else {
        Err(format!("unexpected token {s:?}"))
    }
}

/// Returns the only key/value pair of a single-entry JSON object.
fn single_entry(value: &Value) -> Option<(&str, &Value)> {
    let obj = value.as_object()?;
    if obj.len() != 1 {
        return None;
    }
    obj.iter().next().map(|(k, v)| (k.as_str(), v))
}

fn str_field<'a>(value: &'a Value, key: &str) -> Result<&'a str, String> {
    value
        .get(key)
        .and_then(Value::as_str)
        .ok_or_else(|| format!("missing string field `{key}`"))
}

fn u64_field(value: &Value, key: &str) -> Result<u64, String> {
    value
        .get(key)
        .and_then(Value::as_u64)
        .ok_or_else(|| format!("missing numeric field `{key}`"))
}

fn is_inverted(body: &Value) -> bool {
    body.get("inv").and_then(Value::as_bool).unwrap_or(false)
}

/// Rejects unknown keys so new JSON features cannot be dropped silently.
fn check_keys(body: &Value, allowed: &[&str], what: &str) -> Result<(), String> {
    let obj = body
        .as_object()
        .ok_or_else(|| format!("`{what}` is not an object"))?;
    match obj.keys().find(|k| !allowed.contains(&k.as_str())) {
        Some(k) => Err(format!("unsupported `{what}` option `{k}`")),
        None => Ok(()),
    }
}

/// Collapses a message to one line for use in a `#` comment.
fn single_line(s: &str) -> String {
    s.chars()
        .map(|c| if c.is_control() { ' ' } else { c })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn cmd(value: Value) -> NftCommand {
        NftCommand {
            section: "Test",
            value,
        }
    }

    fn table_and_chain() -> Vec<NftCommand> {
        vec![
            cmd(json!({ "add": { "table": { "family": "inet", "name": "drfw" } } })),
            cmd(json!({ "flush": { "table": { "family": "inet", "name": "drfw" } } })),
            cmd(json!({ "add": { "chain": {
                "family": "inet", "table": "drfw", "name": "input",
                "type": "filter", "hook": "input", "prio": -10, "policy": "drop"
            } } })),
        ]
    }

    fn render_rule_exprs(expr: &Value) -> String {
        let mut cmds = table_and_chain();
        cmds.push(cmd(json!({ "add": { "rule": {
            "family": "inet", "table": "drfw", "chain": "input", "expr": expr
        } } })));
        render(&cmds)
    }

    #[test]
    fn test_header_and_idempotent_preamble() {
        let text = render(&table_and_chain());
        assert!(text.starts_with("#!/usr/sbin/nft -f\n"));
        let table = text.find("\ntable inet drfw\n").expect("table line");
        let delete = text
            .find("\ndelete table inet drfw\n")
            .expect("delete line");
        let block = text.find("table inet drfw {").expect("table block");
        assert!(table < delete && delete < block);
        assert!(text.contains("type filter hook input priority -10; policy drop;"));
    }

    #[test]
    fn test_inverted_limit_and_ct_count() {
        let text = render_rule_exprs(&json!([
            { "limit": { "rate": 5, "per": "minute", "burst": 10, "inv": true } },
            { "ct count": { "val": 3, "inv": true } },
            { "drop": null }
        ]));
        assert!(text.contains("limit rate over 5/minute burst 10 packets ct count over 3 drop"));
    }

    #[test]
    fn test_interface_strings_are_quoted_and_sanitized() {
        let text = render_rule_exprs(&json!([
            { "match": { "left": { "meta": { "key": "iifname" } }, "op": "==",
                         "right": "eth0\" accept\n accept #" } },
            { "accept": null }
        ]));
        assert!(text.contains("iifname \"eth0 accept accept #\" accept"));
        // No line starts with a bare injected "accept"
        assert!(!text.lines().any(|l| l.trim() == "accept"));
    }

    #[test]
    fn test_unsupported_expression_fails_closed() {
        let text = render_rule_exprs(&json!([{ "masquerade": null }]));
        assert!(text.contains(RENDER_ERROR_STATEMENT));
    }

    #[test]
    fn test_unquoted_value_rejects_odd_tokens() {
        let text = render_rule_exprs(&json!([
            { "match": { "left": { "ct": { "key": "state" } }, "op": "==",
                         "right": "established accept" } },
            { "accept": null }
        ]));
        assert!(text.contains(RENDER_ERROR_STATEMENT));
    }

    #[test]
    fn test_values_sets_prefixes_ranges() {
        let text = render_rule_exprs(&json!([
            { "match": { "left": { "payload": { "protocol": "ip6", "field": "saddr" } }, "op": "==",
                         "right": { "set": ["::1", { "prefix": { "addr": "fe80::", "len": 10 } }] } } },
            { "match": { "left": { "payload": { "protocol": "th", "field": "dport" } }, "op": "==",
                         "right": { "set": [22, { "range": [8000, 8080] }] } } },
            { "match": { "left": { "fib": { "flags": ["saddr", "iif"], "result": "oif" } }, "op": "==",
                         "right": false } },
            { "reject": { "type": "icmpx", "expr": "admin-prohibited" } }
        ]));
        assert!(text.contains(
            "ip6 saddr { ::1, fe80::/10 } th dport { 22, 8000-8080 } fib saddr . iif oif missing reject with icmpx type admin-prohibited"
        ));
    }
}
